package main

// in go there are 3 major libraries to build cli applications
// 1. Cobra
// 2. urfave/cli
// 3. bubbletea

// Cobra is the most popular library for building CLI applications in Go.
// It is used by many popular projects such as Kubernetes, Docker, 
// and Hugo. Cobra provides a simple and intuitive API for building 
// CLI applications. It also has a powerful command-line parser that 
// supports subcommands, flags, and arguments.

// urfave/cli is another popular library for building CLI applications
// in Go. It is used by many popular projects such as Terraform 
// and Consul. urfave/cli provides a simple and intuitive API for 
// building CLI applications. It also has a powerful command-line 
// parser that supports subcommands, flags, and arguments.

// bubbletea is a newer library for building CLI applications in 
// Go. It is designed to be simple and easy to use. bubbletea 
